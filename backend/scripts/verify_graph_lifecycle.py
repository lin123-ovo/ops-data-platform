"""Real Postgres/Neo4j lifecycle verification with isolated, mock-extracted documents.

Requires --run-live. Source documents and graph records created here are removed
by their exact generated IDs at the end; existing documents are never modified.
"""
from __future__ import annotations

import argparse
import json
import sys
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sqlalchemy import delete, select
from app.core.postgres import get_session_factory
from app.models import Document, Chunk
from app.models.graph import GraphJob, GraphState
from app.graph.extraction import Extraction
from app.graph.jobs import enqueue
from app.graph.store import get_graph_store
from app.graph.retrieval import graph_paths
from app.graph.worker import process


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run-live', action='store_true')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if not args.run_live:
        raise SystemExit('Use --run-live for isolated verification')
    if args.output.exists():
        raise SystemExit('Refusing to overwrite verification output')
    factory, store = get_session_factory(), get_graph_store()
    prefix = 'graph-lifecycle-'+uuid.uuid4().hex[:8]
    ids = [str(uuid.uuid4()) for _ in range(3)]
    cids = [str(uuid.uuid4()) for _ in range(3)]
    text = '星穹系统依赖清明组件。'
    extraction = Extraction.model_validate({'entities':[{'name':'星穹系统','type':'system'}, {'name':'清明组件','type':'component'}],
        'relations':[{'subject':0,'object':1,'predicate':'DEPENDS_ON','evidence':text}]})
    results = {}
    try:
        for index, (did,cid) in enumerate(zip(ids,cids)):
            with factory() as db, db.begin():
                db.add(Document(id=did, knowledge_base=prefix if index<2 else prefix+'-other', filename='lifecycle.txt', file_type='txt'))
                db.flush()
                db.add(Chunk(id=cid, document_id=did, content=text, chunk_index=0, token_count=10, enabled=True, metadata_json={}))
        def submit(did):
            with factory() as db, db.begin():
                return enqueue(db,did,explicit=True).id
        # Concurrent first build for the SAME document must share a single state and task.
        with ThreadPoolExecutor(max_workers=2) as executor:
            a,b = list(executor.map(submit,[ids[0],ids[0]]))
        results['concurrent_first_build_idempotent'] = a==b
        jobs = [a,submit(ids[1]),submit(ids[2])]
        for job_id in jobs:
            with factory() as db, db.begin():
                job=db.get(GraphJob,job_id)
                # Mark our own task claimed without taking unrelated queue work.
                import time
                job.token=str(uuid.uuid4());job.status='processing';job.attempts=1;job.lease_until=time.time()+180
            process(job_id,factory,store,lambda _: (extraction,{}))
        with factory() as db:
            paths=graph_paths(db,query='星穹系统',chunk_ids=[],knowledge_base=prefix)
            support={a['document_id'] for p in paths for a in p['assertions']}
            results['same_relation_multiple_sources'] = support==set(ids[:2])
            results['knowledge_base_isolation'] = ids[2] not in support
        # Source deletion invalidates reads before any asynchronous cleanup runs.
        with factory() as db, db.begin():
            db.delete(db.get(Document,ids[0]));enqueue(db,ids[0])
        with factory() as db:
            support={a['document_id'] for p in graph_paths(db,query='星穹系统',chunk_ids=[],knowledge_base=prefix) for a in p['assertions']}
            results['deleted_source_hidden_shared_source_retained'] = support=={ids[1]}
        with factory() as db, db.begin():
            db.get(Chunk,cids[1]).enabled=False;enqueue(db,ids[1])
        with factory() as db:
            results['disabled_source_hidden_before_cleanup'] = not graph_paths(db,query='星穹系统',chunk_ids=[],knowledge_base=prefix)
        if not all(results.values()):
            raise RuntimeError('Lifecycle assertion failed')
    finally:
        # Only exact IDs generated by this script; relation nodes from other docs remain intact.
        for did in ids:
            store.cleanup(did)
        with factory() as db, db.begin():
            db.execute(delete(GraphJob).where(GraphJob.document_id.in_(ids)))
            db.execute(delete(GraphState).where(GraphState.document_id.in_(ids)))
            db.execute(delete(Chunk).where(Chunk.document_id.in_(ids)))
            db.execute(delete(Document).where(Document.id.in_(ids)))
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(results,ensure_ascii=False,indent=2))


if __name__=='__main__':
    main()
