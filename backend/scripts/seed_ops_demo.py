SOURCE_DATABASE = 'rag_ops_source_demo'
READER_ROLE = 'rag_ops_source_reader'
SOURCE_WRITE_LOCK = 743580102
DEMO_SERVICES = (
    ('gateway', '采集网关', '平台运维组'),
    ('network', '网络接入', '网络运维组'),
    ('alerts', '告警平台', '监控运维组'),
)
DEMO_TICKET_SERVICES = {'01': 'network', '02': 'gateway', '03': 'gateway', '04': 'network', '05': 'gateway'}
MANUAL_NAME = '运维手册_SLA超时处理.md'
MANUAL = """# 运维手册：SLA 超时工单处理

发现工单超过 SLA 截止时间后，值班人员先核对工单截止时间、当前处理人和服务影响范围。
仍未解决时，把工单升级给值班负责人，补充已完成的排查步骤、下一步操作和预计恢复时间。
有服务中断时先按故障应急流程恢复服务，并在工单内同步进展。
服务恢复后记录实际恢复和解决时间、超时原因及后续改进项，再关闭工单。
"""


def connect(url: URL, *, autocommit: bool = False) -> psycopg.Connection:
    dsn = url.set(drivername='postgresql').render_as_string(hide_password=False)
    return psycopg.connect(dsn, autocommit=autocommit, connect_timeout=5)


def init_source(admin: URL, reader: URL) -> None:
    """Use the local admin for demo provisioning, never in the sync worker."""
    with connect(admin, autocommit=True) as db:
        if db.execute('SELECT 1 FROM pg_roles WHERE rolname = %s', (READER_ROLE,)).fetchone() is None:
            db.execute(sql.SQL('CREATE ROLE {} LOGIN PASSWORD {}').format(
                sql.Identifier(READER_ROLE), sql.Literal(reader.password),
            ))
        if db.execute('SELECT 1 FROM pg_database WHERE datname = %s', (SOURCE_DATABASE,)).fetchone() is None:
            db.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(SOURCE_DATABASE)))
    with connect(admin.set(database=SOURCE_DATABASE)) as db:
        db.execute(sql.SQL('GRANT CONNECT ON DATABASE {} TO {}').format(
            sql.Identifier(SOURCE_DATABASE), sql.Identifier(READER_ROLE),
        ))
        db.execute("""
            CREATE TABLE IF NOT EXISTS public.demo_ticket (
                ticket_id varchar(64) PRIMARY KEY,
                title varchar(250) NOT NULL,
                created_at timestamptz NOT NULL,
                sla_due_at timestamptz NOT NULL,
                resolved_at timestamptz,
                revision bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
            )
        """)
        db.execute('ALTER TABLE public.demo_ticket ADD COLUMN IF NOT EXISTS service_id varchar(64)')
        db.execute("""
            CREATE TABLE IF NOT EXISTS public.demo_service (
                service_id varchar(64) PRIMARY KEY,
                name varchar(120) NOT NULL,
                team varchar(120) NOT NULL,
                revision bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
            )
        """)
        db.execute(sql.SQL('GRANT USAGE ON SCHEMA public TO {}').format(sql.Identifier(READER_ROLE)))
        db.execute(sql.SQL('GRANT SELECT ON public.demo_ticket, public.demo_service TO {}').format(
            sql.Identifier(READER_ROLE),
        ))
    with connect(reader) as db:
        for table in ('public.demo_ticket', 'public.demo_service'):
            readable, writable = db.execute("""
                SELECT has_table_privilege(%s, 'SELECT'),
                       has_table_privilege(%s, 'INSERT,UPDATE,DELETE,TRUNCATE')
            """, (table, table)).fetchone()
            if not readable or writable:
                raise ValueError('模拟源库账号必须具备 SELECT 权限且无写入权限')


def seed_tickets(
    admin: URL, *, add_breach: bool, resolve_on_time: str | None, update_service: list[str] | None,
) -> None:
    monday = last_full_week().start_date
    start = datetime.combine(monday, time(10), OPS_TIMEZONE)
    prefix = monday.strftime('OPS-%Y%m%d')
    with connect(admin.set(database=SOURCE_DATABASE)) as db:
        # Serialize writers so the ordering of committed revisions matches the sync cursor.
        db.execute('SELECT pg_advisory_xact_lock(%s)', (SOURCE_WRITE_LOCK,))
        if update_service is not None:
            service_id, name, team = update_service
            try:
                service = SourceService(service_id=service_id, name=name, team=team, revision=1)
            except ValidationError as exc:
                raise ValueError('服务 ID、名称或责任团队无效') from exc
            updated = db.execute("""
                UPDATE public.demo_service SET name = %s, team = %s, revision = DEFAULT
                WHERE service_id = %s AND (name, team) IS DISTINCT FROM (%s, %s)
            """, (service.name, service.team, service.service_id, service.name, service.team)).rowcount
            if not updated and db.execute(
                'SELECT 1 FROM public.demo_service WHERE service_id = %s', (service.service_id,),
            ).fetchone() is None:
                raise ValueError('指定的演示服务不存在')
            return
        if resolve_on_time is not None:
            updated = db.execute("""
                UPDATE public.demo_ticket
                SET resolved_at = sla_due_at, revision = DEFAULT
                WHERE ticket_id = %s AND resolved_at IS DISTINCT FROM sla_due_at
            """, (resolve_on_time,)).rowcount
            if not updated:
                exists = db.execute(
                    'SELECT 1 FROM public.demo_ticket WHERE ticket_id = %s', (resolve_on_time,),
                ).fetchone()
                if exists is None:
                    raise ValueError('指定的演示工单不存在')
            return
        if not add_breach:
            for service in DEMO_SERVICES:
                db.execute("""
                    INSERT INTO public.demo_service (service_id, name, team)
                    VALUES (%s, %s, %s) ON CONFLICT (service_id) DO NOTHING
                """, service)
            for suffix, service_id in DEMO_TICKET_SERVICES.items():
                db.execute("""
                    UPDATE public.demo_ticket SET service_id = %s, revision = DEFAULT
                    WHERE service_id IS NULL AND ticket_id ~ %s
                """, (service_id, rf'^OPS-[0-9]{{8}}-{suffix}$'))
        samples = [
            ('01', '网络巡检告警', start, None),
            ('02', '采集网关故障', start + timedelta(days=1), timedelta(hours=2)),
            ('03', '应用接口延迟', start + timedelta(days=2), None),
            ('04', '备份任务异常', start + timedelta(days=3), -timedelta(minutes=20)),
            ('05', '日志采集恢复', start + timedelta(days=4), timedelta()),
        ]
        if add_breach:
            samples = [('ADD-' + uuid4().hex[:12], '新增演示超时工单', start, None)]
        for suffix, title, due, resolution in samples:
            db.execute("""
                INSERT INTO public.demo_ticket (ticket_id, title, created_at, sla_due_at, resolved_at, service_id)
                VALUES (%s, %s, %s, %s, %s, %s) ON CONFLICT (ticket_id) DO NOTHING
            """, (f'{prefix}-{suffix}', title, due - timedelta(hours=2), due,
                  due + resolution if resolution is not None else None,
                  'gateway' if add_breach else DEMO_TICKET_SERVICES[suffix]))
    print(f'合成工单已写入，统计周起始日 {monday}。')


def seed_manual() -> None:
    with get_session_factory()() as db:
        existing = db.scalars(
            select(Document).where(
                Document.knowledge_base == OPS_KNOWLEDGE_BASE, Document.filename == MANUAL_NAME,
            ).limit(1),
        ).first()
        if existing is None:
            document = DocumentService(db).ingest_text(
                filename=MANUAL_NAME, content=MANUAL, knowledge_base=OPS_KNOWLEDGE_BASE,
            )
            print(f'运维手册已入库，文档 ID {document.id}。')
        else:
            print(f'运维手册已存在，文档 ID {existing.id}。')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--add-breach', action='store_true')
    modes.add_argument('--resolve-on-time', metavar='TICKET_ID')
    modes.add_argument('--update-service', nargs=3, metavar=('SERVICE_ID', 'NAME', 'TEAM'))
    parser.add_argument('--tickets-only', action='store_true')
    args = parser.parse_args()
    settings = get_settings()
    if settings.ops_source_dsn is None:
        raise SystemExit('请设置 OPS_SOURCE_DSN')
    admin = make_url(settings.postgres_dsn)
    reader = make_url(settings.ops_source_dsn.get_secret_value())
    if (
        reader.database != SOURCE_DATABASE or reader.username != READER_ROLE or not reader.password
        or reader.host not in {'127.0.0.1', 'localhost', '::1'}
        or admin.host not in {'127.0.0.1', 'localhost', '::1'}
        or (reader.port or 5432) != (admin.port or 5432)
    ):
        raise SystemExit('OPS_SOURCE_DSN 必须指向同一台本机 PostgreSQL 上的专用源库和只读用户')
    initialize = not (args.add_breach or args.resolve_on_time or args.update_service)
    try:
        if initialize:
            init_source(admin, reader)
        seed_tickets(
            admin, add_breach=args.add_breach, resolve_on_time=args.resolve_on_time,
            update_service=args.update_service,
        )
    except psycopg.Error as exc:
        raise SystemExit(f'模拟源库操作失败（{type(exc).__name__}），请检查本机连接和账号权限') from None
    except ValueError as exc:
        raise SystemExit(str(exc)) from None
    if initialize and not args.tickets_only:
        seed_manual()


if __name__ == '__main__':
    main()
